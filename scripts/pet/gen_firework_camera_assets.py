"""Generate the small compiled render assets for the fireworks tracking shot.

The approved 410x502 preview in the animation source directory is the single
source of truth. This script reads it, converts the 8x13 rocket sprite to RGB565
plus a transparency mask, copies the seeded speed-line table, and derives the
largest burst magnification that still keeps every effect inside the panel.
Run it after changing any source asset and commit the generated header.
"""

import argparse
import hashlib
import importlib.util
from pathlib import Path

from PIL import Image, ImageSequence


EFFECTS = ("creeper", "star", "sphere", "burst", "rings", "willow", "heart", "snowflake")
SCREEN = (410, 502)
BURST_MS = 1400
BURST_X, BURST_Y = 85, 54
BURST_SAFE_MARGIN = 8
BURST_ZOOM_CAP = 4.7


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def load_preview(source):
    spec = importlib.util.spec_from_file_location(
        "make_tracking_preview", source / "make_tracking_preview.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def rgb565(pixel):
    r, g, b, alpha = pixel
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3) if alpha else 0


def load_rocket(source):
    image = Image.open(source / "firework_rocket.png").convert("RGBA")
    image = image.crop(image.getbbox())
    if image.size != (8, 13):
        raise ValueError(f"Expected the 8x13 rocket after cropping, got {image.size}")
    rows, masks = [], []
    for y in range(image.height):
        pixels, mask = [], 0
        for x in range(image.width):
            pixel = image.getpixel((x, y))
            pixels.append(rgb565(pixel))
            if pixel[3]:
                mask |= 1 << x
        rows.append(pixels)
        masks.append(mask)
    return image.size, rows, masks


def effect_fit_zoom(source, effect, preview):
    """Largest zoom with an 8 px safety margin around the fixed burst anchor."""
    anchor_x, anchor_y = preview.project(BURST_X, BURST_Y, preview.lens(BURST_MS))
    max_zoom = BURST_ZOOM_CAP
    elapsed = 0
    with Image.open(source / f"{effect}.gif") as gif:
        for frame in ImageSequence.Iterator(gif):
            elapsed += frame.info.get("duration", 0)
            if elapsed <= BURST_MS:
                continue
            # Same RGB footprint test as the approved preview: the 160x160 clip
            # has a black background, so getbbox() is the coloured footprint.
            box = frame.convert("RGB").getbbox()
            if not box:
                continue
            left, top, right, bottom = box
            for margin, extent in (
                (anchor_x, BURST_X - left),
                (anchor_y, BURST_Y - top),
                (SCREEN[0] - anchor_x, right - BURST_X),
                (SCREEN[1] - anchor_y, bottom - BURST_Y),
            ):
                if extent > 0:
                    max_zoom = min(max_zoom, (margin - BURST_SAFE_MARGIN) / extent)
    if elapsed != 3500:
        raise ValueError(f"{effect}.gif: expected a 3500 ms timeline, got {elapsed}")
    return max_zoom


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="animation-source/fireworks-v4 directory")
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[2] / "local-only/grok-private-headers/pet_fireworks_assets.h",
        help="generated header path",
    )
    args = parser.parse_args()
    source = args.source.resolve()

    preview = load_preview(source)
    (width, height), pixels, masks = load_rocket(source)
    streaks = preview.STREAKS
    fits = [effect_fit_zoom(source, effect, preview) for effect in EFFECTS]

    lines = [
        "// Generated by scripts/pet/gen_firework_camera_assets.py; do not edit by hand.",
        f"// Source: {source.name}/ (410x502 approved tracking shot, random seed 4831).",
        f"// make_tracking_preview.py sha256={digest(source / 'make_tracking_preview.py')}"
        f" firework_rocket.png sha256={digest(source / 'firework_rocket.png')}",
        "// GIF sha256: " + " ".join(f"{e}={digest(source / (e + '.gif'))}" for e in EFFECTS),
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace pet_fireworks::assets {",
        "",
        f"inline constexpr int kRocketWidth = {width};",
        f"inline constexpr int kRocketHeight = {height};",
        "",
        "// Cropped firework_rocket.png, RGB565, alpha=0 pixels kept as 0.",
        "inline constexpr uint16_t kRocketPixels[kRocketHeight][kRocketWidth] = {",
    ]
    for row in pixels:
        lines.append("    {" + ", ".join(f"0x{value:04x}" for value in row) + "},")
    lines += [
        "};",
        "",
        "// One bit per row pixel, bit 0 = leftmost.",
        "inline constexpr uint8_t kRocketMask[kRocketHeight] = {",
        "    " + ", ".join(f"0x{mask:02x}" for mask in masks) + ",",
        "};",
        "",
        "struct Streak {",
        "    float x;",
        "    float start;",
        "    float depth;",
        "};",
        "",
        "// random.Random(4831) uniform table from the approved preview.",
        "inline constexpr Streak kStreaks[] = {",
    ]
    for x, start, depth in streaks:
        lines.append(f"    {{{x:.4f}f, {start:.4f}f, {depth:.4f}f}},")
    lines += [
        "};",
        f"inline constexpr int kStreakCount = {len(streaks)};",
        "",
        "// Per-effect ceiling that keeps the largest burst footprint on panel.",
        "inline constexpr float kBurstFitZoom[] = {",
        "    " + ", ".join(f"{zoom:.4f}f" for zoom in fits) + ",",
        "};",
        "static_assert(sizeof(kBurstFitZoom) / sizeof(kBurstFitZoom[0]) == 8,",
        '              "one burst fit zoom per effect");',
        "",
        "}  // namespace pet_fireworks::assets",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(args.out)
    print("rocket", width, height, "streaks", len(streaks))
    for effect, zoom in zip(EFFECTS, fits):
        print(f"{effect}: fit zoom {zoom:.4f}")


if __name__ == "__main__":
    main()
