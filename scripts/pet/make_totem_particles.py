"""Generate the deterministic totem particle tables.

The firmware is stateless with respect to particles: every position is a
function of show time and a per-particle descriptor. Generating the table here
keeps the host preview and the device identical and avoids runtime RNG.

Usage:
    python scripts/pet/make_totem_particles.py
"""

import argparse
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

GOLD = (0xFF, 0xD7, 0x5E)
AMBER = (0xF2, 0xB4, 0x3C)
PALE = (0xFF, 0xE9, 0xA8)
GREEN = (0x57, 0xD9, 0x6A)
LIME = (0xA6, 0xF5, 0x8C)


def rgb565(c):
    return ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)


def make_tables(seed=20261110):
    rng = random.Random(seed)
    orbit = []
    for _ in range(128):
        color = rng.choices([GOLD, AMBER, PALE, GREEN, LIME], weights=[30, 18, 10, 28, 14])[0]
        orbit.append({
            "angle": rng.uniform(0.0, 6.2831853),
            "radius": rng.uniform(34.0, 112.0),
            "omega": rng.uniform(0.55, 2.25) * rng.choice([-1.0, 1.0]),
            "size": rng.choice([2.0, 2.0, 3.0, 3.0, 4.0]),
            "lift": rng.uniform(0.0, 26.0),
            "spawn": rng.uniform(0.0, 0.86),
            "color": rgb565(color),
        })
    burst = []
    for _ in range(128):
        color = rng.choices([GOLD, AMBER, PALE, GREEN, LIME], weights=[28, 20, 8, 28, 16])[0]
        burst.append({
            "angle": rng.uniform(0.0, 6.2831853),
            "speed": rng.uniform(150.0, 420.0),
            "size": rng.uniform(3.0, 7.0),
            "life": rng.uniform(0.35, 0.62),
            "drag": rng.uniform(0.25, 0.50),
            "delay": rng.uniform(0.0, 0.045),
            "color": rgb565(color),
        })
    ember = []
    for _ in range(28):
        color = rng.choices([GOLD, AMBER, PALE, GREEN, LIME], weights=[30, 18, 8, 26, 18])[0]
        ember.append({
            "angle": rng.uniform(0.0, 6.2831853),
            "radius": rng.uniform(70.0, 112.0),
            "size": rng.choice([1.0, 2.0, 2.0, 3.0]),
            "delay": rng.uniform(0.20, 0.62),
            "life": rng.uniform(0.55, 1.10),
            "color": rgb565(color),
        })
    return orbit, burst, ember


def fmt(v):
    if isinstance(v, int):
        return f"{v}"
    return f"{v:.4f}f"


def write_header(path, orbit, burst, ember):
    lines = [
        "// Generated by scripts/pet/make_totem_particles.py; do not edit by hand.",
        "// Deterministic descriptors: positions are computed from show time alone.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace pet_totem::particles {",
        "",
        "struct Orbit {",
        "    float angle;",
        "    float radius;",
        "    float omega;",
        "    float size;",
        "    float lift;",
        "    float spawn;",
        "    uint16_t color;",
        "};",
        "",
        "struct Burst {",
        "    float angle;",
        "    float speed;",
        "    float size;",
        "    float life;",
        "    float drag;",
        "    float delay;",
        "    uint16_t color;",
        "};",
        "",
        "struct Ember {",
        "    float angle;",
        "    float radius;",
        "    float size;",
        "    float delay;",
        "    float life;",
        "    uint16_t color;",
        "};",
        "",
        f"inline constexpr Orbit kOrbit[{len(orbit)}] = {{",
    ]
    for p in orbit:
        lines.append("    {" + ", ".join(fmt(p[k]) for k in ("angle", "radius", "omega", "size", "lift", "spawn")) +
                     f", 0x{p['color']:04x}}},")
    lines += ["};", "", f"inline constexpr Burst kBurst[{len(burst)}] = {{"]
    for p in burst:
        lines.append("    {" + ", ".join(fmt(p[k]) for k in ("angle", "speed", "size", "life", "drag", "delay")) +
                     f", 0x{p['color']:04x}}},")
    lines += ["};", "", f"inline constexpr Ember kEmber[{len(ember)}] = {{"]
    for p in ember:
        lines.append("    {" + ", ".join(fmt(p[k]) for k in ("angle", "radius", "size", "delay", "life")) +
                     f", 0x{p['color']:04x}}},")
    lines += ["};", "", "}  // namespace pet_totem::particles", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(ROOT / "main" / "display" / "pet_totem_particles.h"))
    args = parser.parse_args()
    orbit, burst, ember = make_tables()
    write_header(Path(args.out), orbit, burst, ember)
    print(f"wrote {args.out}: orbit={len(orbit)} burst={len(burst)} ember={len(ember)}")


if __name__ == "__main__":
    main()
