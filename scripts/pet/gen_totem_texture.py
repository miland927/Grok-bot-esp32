"""Convert the vanilla 16x16 totem item texture into the firmware RGB565 asset.

Source: the Minecraft 26.2 item texture, 16x16, from
https://blockrender.dev/texture/item/totem_of_undying.png
It is a personal-prototype asset. Replace it with your own art before any
public distribution; see docs/pet/TOTEM.md.

Usage:
    python scripts/pet/gen_totem_texture.py
"""

import argparse
import os
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SOURCE = ROOT / "local-only" / "totem-reference" / "totem-16-original.png"


def rgb565(rgb):
    r, g, b = rgb
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--header", type=Path,
                        default=ROOT / "local-only" / "grok-private-headers" / "pet_totem_assets.h")
    parser.add_argument("--copy", type=Path,
                        default=ROOT / "local-only" / "totem-art" / "totem-source.png")
    parser.add_argument("--preview", type=Path,
                        default=ROOT / "local-only" / "totem-preview" / "totem-16-preview.png")
    args = parser.parse_args()

    image = Image.open(args.source).convert("RGBA")
    if image.size != (16, 16):
        raise SystemExit(f"expected a 16x16 texture, got {image.size}")
    pixels, mask = [], []
    for y in range(16):
        bits = [0, 0]
        for x in range(16):
            r, g, b, a = image.getpixel((x, y))
            if a < 128:
                pixels.append(0)
            else:
                bits[x // 8] |= 1 << (7 - x % 8)
                pixels.append(rgb565((r, g, b)))
        mask.extend(bits)

    texture_header = Path(os.path.relpath(ROOT / "main/display/pet_totem_texture.h",
                                          args.header.resolve().parent)).as_posix()
    lines = [
        "// Generated by scripts/pet/gen_totem_texture.py; do not edit by hand.",
        "// Source: Minecraft 26.2 item texture totem_of_undying (16x16),",
        "// https://blockrender.dev/texture/item/totem_of_undying.png",
        "// Personal prototype only: confirm Mojang/Microsoft asset terms before",
        "// public distribution. Replace the SD pack texture to change the look.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        f'#include "{texture_header}"',
        "",
        "namespace pet_totem::assets {",
        "",
        "inline constexpr int kWidth = 16;",
        "inline constexpr int kHeight = 16;",
        "",
        "inline constexpr uint16_t kPixels[kWidth * kHeight] = {",
    ]
    for y in range(16):
        row = ", ".join(f"0x{pixels[y * 16 + x]:04x}" for x in range(16))
        lines.append(f"    {row},  // {y:2d}")
    lines += [
        "};",
        "",
        "// Two bytes per row, MSB is the leftmost pixel.",
        "inline constexpr int kMaskStride = 2;",
        "inline constexpr uint8_t kMask[kHeight * kMaskStride] = {",
    ]
    for y in range(16):
        lines.append(f"    0x{mask[y * 2]:02x}, 0x{mask[y * 2 + 1]:02x},")
    lines += [
        "};",
        "",
        "inline constexpr Texture kTexture{kPixels, kMask, kWidth, kHeight, kMaskStride};",
        "",
        "}  // namespace pet_totem::assets",
        "",
    ]
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text("\n".join(lines), encoding="utf-8")
    args.copy.parent.mkdir(parents=True, exist_ok=True)
    image.save(args.copy)
    args.preview.parent.mkdir(parents=True, exist_ok=True)
    image.resize((256, 256), Image.NEAREST).save(args.preview)
    print(f"wrote {args.header}")
    print(f"copied {args.copy}")
    print(f"wrote {args.preview}")


if __name__ == "__main__":
    main()
